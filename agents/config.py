MAIN_AXIS_FACTOR = 2.0
# Реальные сети (sim/ или любая .net.xml): у них нет «осей», поэтому вес
# въезда = число полос, жилые улицы (приоритет SUMO < 7) — с коэффициентом
# 0.3. Интенсивность — на единицу веса. ЭТО ПАРАМЕТРЫ ДЛЯ КАЛИБРОВКИ под
