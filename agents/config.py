def _setup_sumo_env() -> None:
    """Находит SUMO, установленный через `pip install eclipse-sumo`.

    sumo-rl требует SUMO_HOME; пакет eclipse-sumo кладёт SUMO внутрь
    site-packages и сообщает путь через атрибут ``sumo.SUMO_HOME``.
    """
    if "SUMO_HOME" not in os.environ:
        try:
            import sumo  # пакет eclipse-sumo

            os.environ["SUMO_HOME"] = sumo.SUMO_HOME
        except ImportError as exc:  # pragma: no cover - понятная ошибка
            raise ImportError(
                "SUMO не найден: выполните `pip install -r agents/requirements.txt` "
                "или задайте переменную окружения SUMO_HOME"
            ) from exc
    bin_dir = os.path.join(os.environ["SUMO_HOME"], "bin")
    if bin_dir not in os.environ.get("PATH", ""):
        os.environ["PATH"] = bin_dir + os.pathsep + os.environ.get("PATH", "")

    # libsumo — та же библиотека SUMO, но вызываемая напрямую, без сокета
    # TraCI. Даёт ускорение в 3–8 раз. Ограничение: одна симуляция на
    # процесс (у нас симуляции и так идут последовательно).
    # Отключить: AGENTS_USE_LIBSUMO=0.
    # Проверяем наличие БЕЗ импорта: libsumo при импорте подтягивает traci,
    # а traci выбирает реализацию (сокет или libsumo) в момент импорта.
    if os.environ.get("AGENTS_USE_LIBSUMO", "1") == "1" and "LIBSUMO_AS_TRACI" not in os.environ:
        import importlib.util

        if importlib.util.find_spec("libsumo") is not None:
            os.environ["LIBSUMO_AS_TRACI"] = "quiet"


_setup_sumo_env()

SUMO_HOME = Path(os.environ["SUMO_HOME"])
SUMO_TOOLS = SUMO_HOME / "tools"
USE_LIBSUMO = os.environ.get("LIBSUMO_AS_TRACI") is not None

# ---------------------------------------------------------------------------
# Синтетические сети (заглушка, пока нет сети из sim/)
